def is_valid(code: str) -> bool:
    """Codes are compared upper-case; the API normalises before it validates, so a client
    sending `pl` is corrected rather than rejected."""
    return code.upper() in NAMES


def name_of(code: str | None) -> str | None:
    return NAMES.get(code.upper()) if code else None
