"""ISO 3166-1 alpha-2, as a constant.

## Why a literal and not a library

`pycountry` would supply this and it is 15 MB of data to answer one question the app
asks in two places. The list below changes about once a decade; a dependency that has to
be audited, pinned and upgraded to track that is a worse trade than a table somebody can
read in a diff.

## Why the app stores the code and not the name

`country_code` holds `PL`, never `Poland`. Codes are stable and names are presentation:
`Türkiye` was `Turkey` until 2022, `Czechia` is still written `Czech Republic` by half the
internet, and any of them may need translating later. Storing the label would mean a data
migration every time a country renames itself, and a `WHERE country = 'Turkey'` that
quietly stops matching. `NAMES` is the display layer and can be rewritten freely.

The English short names below are the display defaults, served to the client so that the
picker and the validator can never disagree about what exists.

**Note the shops table does *not* use this.** `shop.country` is free text, and it stays
that way for now: it feeds the geocoder and an `ilike` filter, both of which want a name.
Aligning the two is a real change with real risk and was not part of this one.
"""

